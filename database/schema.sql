-- V12 PRO : intégrité des paiements. Un frais ne peut jamais être surpayé.
CREATE OR REPLACE FUNCTION fn_verifier_paiement_montant()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE total_existant NUMERIC(12,2);
        montant_frais NUMERIC(12,2);
BEGIN
  SELECT montant_total INTO montant_frais FROM frais_scolaire WHERE id = NEW.frais_id FOR UPDATE;
  IF montant_frais IS NULL THEN RAISE EXCEPTION 'Frais scolaire introuvable.'; END IF;
  SELECT COALESCE(SUM(montant),0) INTO total_existant FROM paiement WHERE frais_id = NEW.frais_id AND id <> COALESCE(NEW.id,0);
  IF total_existant + NEW.montant > montant_frais THEN
    RAISE EXCEPTION 'Paiement refusé : montant supérieur au solde restant dû.';
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_verifier_paiement_montant ON paiement;
CREATE TRIGGER trg_verifier_paiement_montant BEFORE INSERT OR UPDATE ON paiement
FOR EACH ROW EXECUTE FUNCTION fn_verifier_paiement_montant();

