-- TABLE parametre_ecole
-- Ligne unique (id = 1) : identité de l'établissement + branding utilisés dans
-- l'en-tête de l'appli, les bulletins/reçus PDF et les rapports envoyés aux parents.
CREATE TABLE parametre_ecole (
    id INTEGER PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    nom_ecole VARCHAR(150) NOT NULL DEFAULT 'COPEC ISAHA',
    slogan VARCHAR(200),
    adresse VARCHAR(255),
    telephone VARCHAR(30),
