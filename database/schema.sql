-- TABLE pointage_enseignant : présence enseignant. Couvre 2 sources :
--   'manuel'  -> saisi par un agent/admin (comportement d'origine, heure_arrivee/heure_depart)
--   'scan_qr' -> auto-déclaré par l'enseignant (QR salle + GPS + fenêtre horaire), voir colonnes scan_*
CREATE TABLE pointage_enseignant (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enseignant_id INT NOT NULL,
    agent_id INT,
    emploi_du_temps_id INT NOT NULL,
    date_pointage DATE NOT NULL,
    heure_arrivee TIME,
    heure_depart TIME,
    statut VARCHAR(20) NOT NULL CHECK (statut IN ('present', 'absent', 'retard')),
    commentaire TEXT,

    -- Traçabilité / anti-doublon pour la synchronisation offline (uuid généré côté app mobile)
    uuid_local VARCHAR(64) UNIQUE,
    source VARCHAR(20) NOT NULL DEFAULT 'manuel' CHECK (source IN ('manuel', 'scan_qr')),
    salle_id INT,

    -- Scan d'entrée
    heure_scan_entree TIMESTAMPTZ,       -- horloge du TÉLÉPHONE au moment du scan (timestamp_local envoyé par l'app)
    heure_serveur_entree TIMESTAMPTZ,    -- horloge du SERVEUR à la réception de la requête (référence fiable)
    gps_lat_entree DECIMAL(10,7),
    gps_lng_entree DECIMAL(10,7),
    gps_precision_entree DECIMAL(6,1),
    gps_mock_entree BOOLEAN NOT NULL DEFAULT FALSE,

    -- Scan de sortie
    heure_scan_sortie TIMESTAMPTZ,       -- horloge du TÉLÉPHONE (timestamp_local)
    heure_serveur_sortie TIMESTAMPTZ,    -- horloge du SERVEUR à la réception
    gps_lat_sortie DECIMAL(10,7),
    gps_lng_sortie DECIMAL(10,7),
    gps_precision_sortie DECIMAL(6,1),
    gps_mock_sortie BOOLEAN NOT NULL DEFAULT FALSE,

    -- Preuve de vérification selfie (2e facteur) réalisée juste avant le scan
    selfie_verifie_a TIMESTAMPTZ,
    selfie_score DECIMAL(5,4),
    selfie_verifie_a_sortie TIMESTAMPTZ,
    selfie_score_sortie DECIMAL(5,4),

    -- Calculs dérivés (précis, en minutes)
    retard_minutes INT NOT NULL DEFAULT 0 CHECK (retard_minutes >= 0),
    depart_anticipe_minutes INT NOT NULL DEFAULT 0 CHECK (depart_anticipe_minutes >= 0),
    duree_reelle_minutes INT CHECK (duree_reelle_minutes IS NULL OR duree_reelle_minutes >= 0),
    duree_payee_minutes INT CHECK (duree_payee_minutes IS NULL OR duree_payee_minutes >= 0),

    -- Cas "entrée sans sortie" (ou tout autre cas ambigu) : nécessite arbitrage admin
    statut_validation VARCHAR(25) NOT NULL DEFAULT 'auto'
        CHECK (statut_validation IN ('auto', 'en_attente_validation', 'valide_admin', 'rejete')),
    raison_refus VARCHAR(50),
    valide_par_id INT,
    valide_par_agent_id INT,
    date_validation TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_pointage_ens UNIQUE (enseignant_id, emploi_du_temps_id, date_pointage),
    CONSTRAINT fk_pe_enseignant FOREIGN KEY (enseignant_id) REFERENCES utilisateur(id) ON DELETE CASCADE,
    -- SET NULL (et non CASCADE) : cohérent avec toutes les autres FK "agent_id"
    -- de la base (paiement, notification, actualite, depense, discipline, ...).
    -- Supprimer un agent ne doit jamais effacer l'historique de pointage des enseignants.
    CONSTRAINT fk_pe_agent FOREIGN KEY (agent_id) REFERENCES agent(id) ON DELETE SET NULL,
    -- RESTRICT (et non SET NULL) : emploi_du_temps_id est NOT NULL ci-dessus, donc SET NULL
    -- provoquait une erreur PostgreSQL au premier DELETE d'un créneau EDT déjà pointé.
    CONSTRAINT fk_pe_edt FOREIGN KEY (emploi_du_temps_id) REFERENCES emploi_du_temps(id) ON DELETE RESTRICT,
    CONSTRAINT fk_pe_salle FOREIGN KEY (salle_id) REFERENCES salle(id) ON DELETE SET NULL,
    CONSTRAINT fk_pe_valide_par FOREIGN KEY (valide_par_id) REFERENCES utilisateur(id) ON DELETE SET NULL,
    CONSTRAINT fk_pe_valide_par_agent FOREIGN KEY (valide_par_agent_id) REFERENCES agent(id) ON DELETE SET NULL
);

