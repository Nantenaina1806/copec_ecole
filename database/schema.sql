-- Intégrité (ex-migration V6) : une paie payée ne peut pas être recréditée silencieusement.
CREATE OR REPLACE FUNCTION fn_proteger_paie_payee()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.statut = 'paye' AND (
    NEW.enseignant_id IS DISTINCT FROM OLD.enseignant_id OR
    NEW.mois IS DISTINCT FROM OLD.mois OR
    NEW.annee IS DISTINCT FROM OLD.annee OR
    NEW.salaire_net IS DISTINCT FROM OLD.salaire_net OR
    NEW.heures_normales IS DISTINCT FROM OLD.heures_normales OR
    NEW.heures_supplementaires IS DISTINCT FROM OLD.heures_supplementaires
  ) THEN
    RAISE EXCEPTION 'Bulletin de paie déjà payé : modification financière interdite. Annulez/régularisez par une pièce comptable explicite.';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_proteger_paie_payee
BEFORE UPDATE ON paie FOR EACH ROW EXECUTE FUNCTION fn_proteger_paie_payee();

-- TABLE tarif_frais
-- Grille tarifaire de référence : montant attendu par niveau, par type de frais, pour une
