    demo_whatsapp_daily_limit INTEGER NOT NULL DEFAULT 5 CHECK (demo_whatsapp_daily_limit >= 0),
    backup_retention_days INTEGER NOT NULL DEFAULT 30 CHECK (backup_retention_days >= 1),
