-- Contrôle des horaires de l'EDT : aucun chevauchement pour une classe
-- ou un enseignant dans la même année scolaire.
CREATE OR REPLACE FUNCTION fn_check_edt_overlap()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM emploi_du_temps e
        WHERE e.id <> COALESCE(NEW.id, 0)
          AND e.actif = TRUE
          AND NEW.actif = TRUE
          AND e.annee_scolaire_id = NEW.annee_scolaire_id
          AND e.jour = NEW.jour
          AND (
              (e.classe_id = NEW.classe_id AND e.matiere_id = NEW.matiere_id)
              OR (
                  (
                      e.classe_id = NEW.classe_id
                      OR e.enseignant_id = NEW.enseignant_id
                      OR (NEW.salle_id IS NOT NULL AND e.salle_id = NEW.salle_id)
                  )
                  AND NEW.heure_debut < e.heure_fin
                  AND NEW.heure_fin > e.heure_debut
              )
          )
    ) THEN
        RAISE EXCEPTION 'Chevauchement emploi du temps: classe ou enseignant déjà occupé (%) %-%',
            NEW.jour, NEW.heure_debut, NEW.heure_fin;
    END IF;
    RETURN NEW;
END;
$$;

