-- Vérifie que le paiement ne dépasse pas le montant du frais.
CREATE OR REPLACE FUNCTION fn_check_paiement_montant()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    total_paye NUMERIC(12,2);
    montant_frais NUMERIC(12,2);
BEGIN
    SELECT montant_total INTO montant_frais
    FROM frais_scolaire
    WHERE id = NEW.frais_id;

    SELECT COALESCE(SUM(p.montant), 0) INTO total_paye
    FROM paiement p
    WHERE p.frais_id = NEW.frais_id
