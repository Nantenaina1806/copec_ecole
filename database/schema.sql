-- Vue pratique : solde théorique de chaque caisse.
CREATE OR REPLACE VIEW v_solde_caisse AS
SELECT c.id, c.nom, c.solde_initial,
       c.solde_initial
       + COALESCE(SUM(CASE WHEN m.type_mouvement='entree' THEN m.montant ELSE -m.montant END),0) AS solde_theorique
FROM caisse c
LEFT JOIN mouvement_caisse m ON m.caisse_id = c.id
GROUP BY c.id, c.nom, c.solde_initial;

